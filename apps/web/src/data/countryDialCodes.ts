export const DEFAULT_DIAL_ISO = "CD";

export function flagEmoji(iso2: string) {
  return iso2
    .toUpperCase()
    .replace(/./g, (char) => String.fromCodePoint(127397 + char.charCodeAt(0)));
}

export function findCountryByIso(iso2: string) {
  return COUNTRY_DIAL_CODES.find((c) => c.iso2 === iso2);
}

export function composePhone(dial: string, national: string) {
  const digits = national.replace(/\D/g, "").replace(/^0+/, "");
  if (!digits) return "";
  return `+${dial}${digits}`;
}

export function splitPhone(value: string | undefined | null): {
  iso2: string;
  national: string;
} {
  const raw = (value ?? "").trim();
  if (!raw) {
    return { iso2: DEFAULT_DIAL_ISO, national: "" };
  }

  const digits = raw.replace(/\D/g, "");
  const sorted = [...COUNTRY_DIAL_CODES].sort(
    (a, b) => b.dial.length - a.dial.length,
  );

  for (const country of sorted) {
    if (digits.startsWith(country.dial)) {
      return {
        iso2: country.iso2,
        national: digits.slice(country.dial.length),
      };
    }
  }

  return { iso2: DEFAULT_DIAL_ISO, national: digits };
}
